package com.purrfolio.mco1;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Calendar;
import java.util.List;
import java.util.Locale;
import org.junit.Test;

/** Run in Android Studio: right-click this file → Run 'RecordExportTest'. */
public class RecordExportTest {
    private static final long NOW = at(2026, Calendar.NOVEMBER, 21, 10);

    private static long at(int year, int month, int day, int hour) {
        Calendar c = Calendar.getInstance();
        c.clear();
        c.set(year, month, day, hour, 0, 0);
        return c.getTimeInMillis();
    }

    private static final Pet MOCHI = new Pet("mochi", "Mochi", "Cat", "Persian", "2024-03-10", "Female", "4.2", "",
            "", "Allergic to chicken", "Happy Paws Clinic", "02 8123 4567", "", "", "", "985 112 003");
    private static final RecordExport.Owner OWNER = new RecordExport.Owner("Theo", "+63 912 345 6789", "theo@example.com");

    private static final List<PetRecord> RECORDS = Arrays.asList(
            new PetRecord("1", "mochi", PetRecord.Type.CARE_LOGS, "Feeding", "1/2 cup kibble", at(2026, Calendar.NOVEMBER, 20, 8), ""),
            new PetRecord("2", "mochi", PetRecord.Type.MEDICATIONS, "Medication", "Deworming tablet", at(2026, Calendar.NOVEMBER, 2, 9), ""),
            new PetRecord("3", "mochi", PetRecord.Type.MEDICATIONS, "Vitamins", "", at(2026, Calendar.NOVEMBER, 18, 9), ""),
            new PetRecord("4", "mochi", PetRecord.Type.CARE_LOGS, "Grooming", "Brushed", PetRecord.UNKNOWN_TIME, ""));

    private static RecordExport.Summary build(RecordExport.Options options) {
        return RecordExport.build(MOCHI, OWNER, RECORDS, "All types · This Month", options, NOW, Locale.US);
    }

    private static List<String> headings(RecordExport.Summary summary) {
        List<String> headings = new ArrayList<>();
        for (RecordExport.Section s : summary.sections) headings.add(s.heading);
        return headings;
    }

    @Test public void titleSubtitleAndFileName() {
        RecordExport.Summary summary = build(new RecordExport.Options());
        assertEquals("Mochi's Records", summary.title);
        assertEquals("4 records · All types · This Month", summary.subtitle);
        assertEquals("Mochi-records-2026-11-21", summary.fileBaseName);
        assertEquals("Generated by Purrfolio on Nov 21, 2026", summary.footer);
    }

    @Test public void ownerContactIsOffByDefault() {
        RecordExport.Summary summary = build(new RecordExport.Options());
        assertEquals(Arrays.asList("Pet Details", "Medications (2)", "Care Logs (2)"), headings(summary));
        assertFalse(RecordExport.toText(summary).contains("theo@example.com"));
    }

    @Test public void ownerContactWhenSwitchedOn() {
        RecordExport.Options options = new RecordExport.Options();
        options.includeOwnerContact = true;
        RecordExport.Summary summary = build(options);
        assertEquals(Arrays.asList("Owner: Theo", "Phone: +63 912 345 6789", "Email: theo@example.com"),
                summary.sections.get(1).lines);
    }

    @Test public void petDetailsSkipEmptyFieldsAndShowAge() {
        List<String> lines = build(new RecordExport.Options()).sections.get(0).lines;
        assertEquals(Arrays.asList("Name: Mochi", "Species: Cat", "Breed: Persian", "Sex: Female",
                "Birthday: Mar 10, 2024 (2 years old)", "Weight: 4.2 kg", "Microchip: 985 112 003",
                "Vet clinic: Happy Paws Clinic · 02 8123 4567", "Medical notes: Allergic to chicken"), lines);
    }

    @Test public void recordsGroupedByTypeNewestFirstUndatedLast() {
        RecordExport.Summary summary = build(new RecordExport.Options());
        assertEquals(Arrays.asList("Nov 18, 2026 · 9:00 AM — Vitamins", "Nov 2, 2026 · 9:00 AM — Medication: Deworming tablet"),
                summary.sections.get(1).lines);
        assertEquals(Arrays.asList("Nov 20, 2026 · 8:00 AM — Feeding: 1/2 cup kibble", "No date — Grooming: Brushed"),
                summary.sections.get(2).lines);
    }

    @Test public void petDetailsAndRecordDetailsCanBeLeftOut() {
        RecordExport.Options options = new RecordExport.Options();
        options.includePetDetails = false;
        options.includeRecordDetails = false;
        RecordExport.Summary summary = build(options);
        assertEquals(Arrays.asList("Medications (2)", "Care Logs (2)"), headings(summary));
        assertEquals("Nov 2, 2026 · 9:00 AM — Medication", summary.sections.get(0).lines.get(1));
    }

    @Test public void noRecordsSaysSo() {
        RecordExport.Options options = new RecordExport.Options();
        options.includePetDetails = false;
        RecordExport.Summary summary = RecordExport.build(MOCHI, OWNER, new ArrayList<>(), "", options, NOW, Locale.US);
        assertEquals("0 records", summary.subtitle);
        assertEquals(Arrays.asList("No records match these filters."), summary.sections.get(0).lines);
    }

    @Test public void textFormat() {
        RecordExport.Options options = new RecordExport.Options();
        options.includePetDetails = false;
        String text = RecordExport.toText(build(options));
        assertTrue(text.startsWith("Mochi's Records\n4 records · All types · This Month\n\nMedications (2)\n• Nov 18, 2026"));
        assertTrue(text.endsWith("\nGenerated by Purrfolio on Nov 21, 2026\n"));
    }

    @Test public void fileNamesAreSafe() {
        assertEquals("Mr-Whiskers", RecordExport.safeFileName(" Mr. Whiskers! "));
        assertEquals("Pet", RecordExport.safeFileName("???"));
    }
}
